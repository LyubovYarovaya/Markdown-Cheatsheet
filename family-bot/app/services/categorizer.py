_WORD_RE = re.compile(r"[^\w]+", re.UNICODE)


@dataclass(slots=True)
class Guess:
    slug: str
    score: int

    @property
    def confident(self) -> bool:
        return self.score >= 2


def guess_category(title: str | None = None, url: str | None = None) -> Guess:
    """Возвращает slug категории покупок и грубую оценку уверенности."""
    haystack = " ".join(p for p in (title, url) if p).lower()
    if not haystack:
        return Guess("other", 0)

    scores: dict[str, int] = {}
    for slug, words in KEYWORDS.items():
        hits = sum(1 for w in words if w in haystack)
        if hits:
            # Совпадение в названии весит больше, чем случайное вхождение в URL.
            in_title = bool(title) and any(w in title.lower() for w in words)
            scores[slug] = hits * 2 + (2 if in_title else 0)

    lowered_url = (url or "").lower()
    for slug, hints in URL_HINTS.items():
        hits = sum(1 for h in hints if h in lowered_url)
        if hits:
            scores[slug] = scores.get(slug, 0) + hits * 2

    if not scores:
        return Guess("other", 0)

    slug = max(scores, key=lambda k: scores[k])
    return Guess(slug, scores[slug])


