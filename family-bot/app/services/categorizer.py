def guess_expense_category(text: str) -> str:
    """Определяет категорию траты по свободному тексту."""
    lowered = f" {text.lower()} "
    best, best_hits = "other", 0
    for slug, words in EXPENSE_KEYWORDS.items():
        hits = sum(1 for w in words if w in lowered)
        if hits > best_hits:
            best, best_hits = slug, hits
    return best


def tokenize(text: str) -> list[str]:
    return [t for t in _WORD_RE.split(text.lower()) if t]
